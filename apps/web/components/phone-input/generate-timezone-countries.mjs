// Regenerates timezone-countries.generated.ts from the tz database bundled with moment-timezone:
//   node apps/web/components/phone-input/generate-timezone-countries.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { isSupportedCountry } from "libphonenumber-js";

const require = createRequire(import.meta.url);
const meta = require("moment-timezone/data/meta/latest.json");
const packed = require("moment-timezone/data/packed/latest.json");
const { version } = JSON.parse(readFileSync(require.resolve("moment-timezone/package.json"), "utf8"));

// A merged zone lists every country it covers (Europe/Brussels: BE, LU, NL); the first one is its own.
// Zones of places without a calling code of their own (Antarctica, Kerguelen…) are left out.
const countryOf = (zone) => {
  const country = meta.zones[zone]?.countries[0];
  return country && isSupportedCountry(country) ? country : undefined;
};

const map = new Map();
for (const zone of Object.keys(meta.zones)) {
  const country = countryOf(zone);
  if (country) map.set(zone, country);
}
// Browsers may report legacy or linked names (ICU keeps Asia/Calcutta, Europe/Kiev, Europe/Amsterdam).
// moment-timezone does not always link old to new (Europe/Kiev|Europe/Kyiv), so either name may be the known one.
for (const link of packed.links) {
  const [a, b] = link.split("|");
  if (!map.has(b) && map.has(a)) map.set(b, map.get(a));
  if (!map.has(a) && map.has(b)) map.set(a, map.get(b));
}

const entries = [...map.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, country]) => `  "${zone}": "${country.toLowerCase()}",`)
  .join("\n");

const out = `// Generated by generate-timezone-countries.mjs from moment-timezone ${version} (tzdata ${meta.version}). Do not edit.
export const TIMEZONE_COUNTRIES: Readonly<Record<string, string>> = {
${entries}
};
`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "timezone-countries.generated.ts"), out);
console.log(`${map.size} time zones`);
